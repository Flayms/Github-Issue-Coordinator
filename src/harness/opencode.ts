/**
 * The OpenCode Harness (REQ-006-14): interactive `opencode --mini` sessions with every permission allowed (REQ-005-01).
 * OpenCode has no shell hooks, only JS plugins, so a small plugin in the session folder runs the hook script on
 * OpenCode's events. It loads with a per-session config folder (`OPENCODE_CONFIG_DIR`), so nothing is written into the
 * Worktree or the user's config. Checked with OpenCode 1.19.6 against a fake model server and a free Zen model
 * (docs/harnesses.md).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RoleSettings } from "../config.ts";
import type { Harness } from "./harness.ts";

/** Model values in the Model catalogue carry this prefix: `opencode:<provider>/<model>`, e.g. `opencode:opencode/big-pickle`. */
export const OPENCODE_MODEL_PREFIX = "opencode:";

/** The hook events the plugin fires: Claude Code's names and fields, plus OpenCode's own retry status. */
export const OPENCODE_HOOK_EVENTS = ["SessionStart", "UserPromptSubmit", "Stop", "session.status"] as const;

/**
 * REQ-006-15: OpenCode retries a rate-limited model call forever (`session.status` `retry`, after the provider's
 * `retry-after`), so the Coordinator takes the third retry of a rate limit for the usage limit.
 */
export const OPENCODE_LIMIT_RETRIES = 3;
const LIMIT_MESSAGE = /rate.?limit|quota|too many requests|\b429\b|usage limit/i;

const configDir = (sessionDir: string) => join(sessionDir, "opencode");

/** `<provider>/<model>` as `opencode --model` takes it. */
export const opencodeModel = (model: string): string =>
  model.startsWith(OPENCODE_MODEL_PREFIX) ? model.slice(OPENCODE_MODEL_PREFIX.length) : model;

/** REQ-006-15: a retry status of OpenCode's that is the usage limit: a rate limit or quota, retried a third time. */
export function isOpenCodeUsageLimit(status: unknown): boolean {
  if (typeof status !== "object" || status === null) return false;
  const { type, attempt, message } = status as Record<string, unknown>;
  return (
    type === "retry" &&
    typeof attempt === "number" &&
    attempt >= OPENCODE_LIMIT_RETRIES &&
    typeof message === "string" &&
    LIMIT_MESSAGE.test(message)
  );
}

/**
 * The plugin's hook payloads in the shape src/hook.ts handles: the model gets the catalogue's prefix (REQ-001-29), and
 * a retry status that is the usage limit becomes StopFailure with `error: "rate_limit"`. Undefined for any other retry.
 */
export function opencodeHookInput(
  event: string,
  payload: Record<string, unknown>,
): { event: string; payload: Record<string, unknown> } | undefined {
  if (event === "SessionStart" && typeof payload.model === "string")
    return { event, payload: { ...payload, model: `${OPENCODE_MODEL_PREFIX}${payload.model}` } };
  if (event === "session.status")
    return isOpenCodeUsageLimit(payload.status)
      ? { event: "StopFailure", payload: { ...payload, error: "rate_limit" } }
      : undefined;
  return { event, payload };
}

/**
 * The plugin, rewritten on every launch. It runs the hook commands with the payload on stdin, one at a time and in
 * the order of OpenCode's events, and acts on their answer: a blocked Stop's reason becomes the next prompt, and
 * `abort` ends a turn the usage limit stopped. Subagent sessions are left alone. A turn the Owner interrupted (or the
 * plugin aborted) gets no Stop, as with Claude Code. Errors go to `hook-errors.log` in the session folder.
 */
export function opencodePlugin(hooks: Record<string, string>, errorLog: string): string {
  return `// Coordinator session hooks for OpenCode, generated by the Coordinator (src/harness/opencode.ts).
import { appendFileSync } from "node:fs";

const HOOKS = ${JSON.stringify(hooks, null, 2)};
const ERRORS = ${JSON.stringify(errorLog)};

export const CoordinatorSession = async ({ client }) => {
  const children = new Set();
  const started = new Set();
  const ended = new Set();
  let queue = Promise.resolve();
  const log = (e) => {
    try {
      appendFileSync(ERRORS, \`\${new Date().toISOString()} opencode plugin \${String(e?.stack ?? e)}\\n\`);
    } catch {}
  };
  // One hook at a time, in event order. Handlers never wait on the queue: OpenCode may wait on them.
  const later = (fn) => {
    const job = queue.then(fn);
    queue = job.catch(log);
    return job;
  };
  const run = async (event, payload) => {
    const p = Bun.spawn(["sh", "-c", HOOKS[event]], { stdin: "pipe", stdout: "pipe", stderr: "ignore" });
    p.stdin.write(JSON.stringify({ hook_event_name: event, ...payload }));
    p.stdin.end();
    const out = (await new Response(p.stdout).text()).trim();
    await p.exited;
    return out ? JSON.parse(out) : {};
  };
  return {
    "chat.message": async (input, output) => {
      const id = input.sessionID;
      if (children.has(id)) return;
      const model = input.model ? \`\${input.model.providerID}/\${input.model.modelID}\` : undefined;
      const prompt = output.parts
        .filter((p) => p.type === "text" && !p.synthetic)
        .map((p) => p.text)
        .join("\\n");
      later(async () => {
        ended.delete(id);
        if (!started.has(id)) {
          started.add(id);
          await run("SessionStart", { session_id: id, model });
        }
        await run("UserPromptSubmit", { session_id: id, prompt });
      }).catch(() => {});
    },
    event: async ({ event }) => {
      const p = event.properties ?? {};
      if (event.type === "session.created" && p.info?.parentID) children.add(p.info.id);
      const id = p.sessionID;
      if (!id || children.has(id)) return;
      if (event.type === "session.error" && p.error?.name === "MessageAbortedError") ended.add(id);
      if (event.type === "session.status" && p.status?.type === "retry")
        later(async () => {
          if (ended.has(id)) return;
          const out = await run("session.status", { session_id: id, status: p.status });
          if (!out.abort) return;
          ended.add(id);
          client.session.abort({ path: { id } }).catch(log);
        }).catch(() => {});
      if (event.type === "session.idle")
        later(async () => {
          if (ended.delete(id)) return undefined;
          return run("Stop", { session_id: id });
        })
          .then((out) => {
            if (out?.decision !== "block") return;
            const parts = [{ type: "text", text: out.reason }];
            return client.session.promptAsync({ path: { id }, body: { parts } });
          })
          .catch(log);
    },
  };
};
`;
}

/** The per-session config: every permission allowed, no sharing or updates; the Role's effort as the model's variant. */
export function opencodeConfig(model: RoleSettings | undefined): Record<string, unknown> {
  const config: Record<string, unknown> = {
    $schema: "https://opencode.ai/config.json",
    permission: "allow",
    share: "disabled",
    autoupdate: false,
  };
  // `opencode --mini` has no flag for the variant; the default agent's, with the same model, applies (OpenCode 1.19.6).
  if (model?.effort) config.agent = { build: { model: opencodeModel(model.model), variant: model.effort } };
  return config;
}

export const opencode: Harness = {
  name: "opencode",
  label: "OpenCode",
  bin: "opencode",
  minVersion: "1.19.6",
  features: {
    launch: { has: true, how: "`--auto`, `permission: allow`" },
    resume: { has: true, how: "`--session <id>`" },
    turnEndHook: { has: true, how: "plugin on `session.idle`" },
    loginCheck: { has: true, how: "`opencode models`" },
    remoteControl: {
      has: false,
      why: "OpenCode's `serve` / `web` could open a session in a browser; not wired up yet",
    },
    nowLine: { has: false, why: "OpenCode keeps sessions in a SQLite database, not a transcript file; not read yet" },
    usageQuota: { has: false, why: "OpenCode reports no quota of the provider" },
    usageLimit: { has: true, how: "plugin on a `retry` status" },
    usageLimitReset: {
      has: false,
      why: "OpenCode only says when it retries; the Account pauses for the default interval",
    },
    transcriptMove: {
      has: false,
      why:
        "one Account only: logins and sessions share OpenCode's data folder, which only `XDG_DATA_HOME` moves, " +
        "and that would move every other tool's data in the session too",
    },
  },
  // No accountEnv: one Account in OpenCode's default data folder (REQ-006-16).
  defaultAccountFolder: join(".local", "share", "opencode"),
  dialogs: [],

  writeSessionConfig({ sessionDir, hook, model }) {
    const dir = configDir(sessionDir);
    mkdirSync(join(dir, "plugins"), { recursive: true });
    writeFileSync(join(dir, "opencode.json"), JSON.stringify(opencodeConfig(model), null, 2));
    const hooks = Object.fromEntries(OPENCODE_HOOK_EVENTS.map((ev) => [ev, hook(ev)]));
    writeFileSync(join(dir, "plugins", "issueflow.js"), opencodePlugin(hooks, join(sessionDir, "hook-errors.log")));
  },

  args({ model, resumeId }) {
    // `--session <id>` exits on an unknown id; `--continue` would take the latest session, ambiguous across Worktrees.
    const args: string[] = resumeId ? ["--session", resumeId] : [];
    // `--mini`: the full TUI ignores `--prompt` when it opens an existing session. REQ-005-01: `--auto` approves
    // whatever the config doesn't deny, e.g. a Worktree's own `opencode.json`.
    args.push("--mini", "--auto", "--model", opencodeModel(model.model));
    // The runner appends the prompt.
    args.push("--prompt");
    return args;
  },

  // The per-session config folder, read besides the user's own config.
  env: ({ sessionDir }) => ({ OPENCODE_CONFIG_DIR: configDir(sessionDir) }),

  // Free Zen models need no login, so the check is that OpenCode offers a model at all.
  loginCheck: {
    args: ["models"],
    read: ({ ok, out }) => {
      const models = out.split("\n").filter((l) => /^\S+\/\S+$/.test(l.trim())).length;
      return ok && models > 0
        ? { ok, detail: `${models} models` }
        : { ok: false, detail: "run it with `providers login`, or set a provider's API key" };
    },
  },

  hookInput: opencodeHookInput,

  // REQ-006-15: the plugin aborts the turn OpenCode would otherwise retry forever.
  hookOutput: (event, stdout) => (event === "StopFailure" ? JSON.stringify({ abort: true }) : stdout),
};
